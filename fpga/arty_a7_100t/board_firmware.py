#!/usr/bin/env python3
"""The Arty A7-100T board image (roadmap R3.3, first boot profile).

A bare-metal program for boot mode 2, assembled with the same assembler as the
simulation firmware (sim/scripts/soc_firmware.py), so it needs no compiler:

  1. Print "LS" and RESET_SRC as a digit on the UART: 0 after a cold start,
     1 after an early kick, 2 after a timeout.
  2. Wait for the watchdog window to open, kick, wait for the kick to land,
     and print "." for each kick, for ever.

On a bench this shows reset release, the first instructions, the watchdog
window and a running program, on the UART alone. Regenerate the image with:

    python fpga/arty_a7_100t/board_firmware.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "sim" / "scripts"))

import soc_firmware as fw  # noqa: E402 - needs the path above

OUTPUT = HERE / "board_imem_image.vhd"

BOARD_PROGRAM = [
    ("jal", "zero", "main"),

    # No interrupt is enabled, so a trap can only be an access fault. Count it
    # in s5 and go on with the next instruction.
    "trap:",
    ("addi", "s5", "s5", 1),
    ("csrr", "t3", "mepc"),
    ("addi", "t3", "t3", 4),
    ("csrw", "mepc", "t3"),
    ("mret",),

    "main:",
    ("lui", "s0", 0x40000),            # s0 = peripheral window
    ("lui", "s4", 0xE),                # s4 = watchdog key, 0xDEAD
    ("addi", "s4", "s4", -339),
    ("addi", "s5", "zero", 0),
    ("addi", "t0", "zero", fw.TRAP_ADDRESS),
    ("csrw", "mtvec", "t0"),

    # The banner, then RESET_SRC as a digit
    ("addi", "a0", "zero", ord("L")),
    ("jal", "s1", "putc"),
    ("addi", "a0", "zero", ord("S")),
    ("jal", "s1", "putc"),
    ("lw", "t1", 0x208, "s0"),
    ("addi", "a0", "t1", ord("0")),
    ("jal", "s1", "putc"),

    # Kick in every window, and say so
    "loop:",
    ("addi", "t2", "zero", fw.WD_WINDOW_OPEN),
    "wait_window:",
    ("lw", "t1", 0x204, "s0"),
    ("andi", "t1", "t1", 0x1F),
    ("bne", "t1", "t2", "wait_window"),
    ("sw", "s4", 0x200, "s0"),
    "wait_kick:",
    ("lw", "t1", 0x204, "s0"),
    ("andi", "t1", "t1", 0x1F),
    ("beq", "t1", "t2", "wait_kick"),
    ("addi", "a0", "zero", ord(".")),
    ("jal", "s1", "putc"),
    ("jal", "zero", "loop"),

    # Send a0 once the UART is free, and return through s1
    "putc:",
    ("lw", "t1", 0x404, "s0"),
    ("andi", "t1", "t1", 1),
    ("bne", "t1", "zero", "putc"),
    ("sw", "a0", 0x400, "s0"),
    ("jalr", "zero", "s1", 0),
]


def main():
    fw.write_image(fw.assemble(BOARD_PROGRAM), OUTPUT,
                   "-- Generated by fpga/arty_a7_100t/board_firmware.py. The Arty A7-100T\n"
                   "-- build's IMEM image, for boot mode 2: a UART banner with RESET_SRC,\n"
                   "-- then a watchdog kick and a dot in every window.\n\n")


if __name__ == "__main__":
    main()
