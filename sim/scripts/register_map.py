#!/usr/bin/env python3
"""The SoC's register map, in one place (roadmap R4.3).

    python sim/scripts/register_map.py

REGISTERS below is the authority for every address the RTL decodes. This
script writes it out three ways:

    config/package_soc_types.vhd   the address constants, between the GENERATED
                                   markers; the rest of the package is untouched
    sw/include/lockstep_soc_regs.h the same addresses for C firmware
    docs/safety/register_map.md    a reference table, with access and meaning

sim/scripts/check_fixtures.py fails if any of the three no longer matches the
table, so an address cannot change in one place only. The published addresses
are those of HSI section 3 and 5.1; changing one changes the HSI.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "config" / "package_soc_types.vhd"
HEADER = ROOT / "sw" / "include" / "lockstep_soc_regs.h"
DOC = ROOT / "docs" / "safety" / "register_map.md"

BEGIN = "  -- BEGIN GENERATED by sim/scripts/register_map.py: edit the table there"
END = "-- END GENERATED"

# (VHDL constant, address, block, access, meaning), in the package's order
REGISTERS = [
    ("c_can_id_addr", 0x40000300, "CAN", "RW", "Mailbox identifier, 11 bits"),
    ("c_can_dlc_addr", 0x40000304, "CAN", "RW", "Mailbox data length code"),
    ("c_can_data_addr", 0x40000308, "CAN", "RW", "Mailbox data bytes 0-3, byte 0 in 31:24"),
    ("c_can_status_addr", 0x4000030C, "CAN", "RW", "REC, TEC, interrupt, bus-off, error passive, busy; a word write clears the interrupt"),
    ("c_can_data_hi_addr", 0x40000310, "CAN", "RW", "Mailbox data bytes 4-7, byte 4 in 31:24"),
    ("c_can_tx_request_addr", 0x40000314, "CAN", "W", "A word write sends the mailbox's frame"),
    ("c_can_rx_id_addr", 0x40000318, "CAN", "R", "Received identifier, 11 or 29 bits"),
    ("c_can_rx_info_addr", 0x4000031C, "CAN", "R", "5 extended, 4 remote, 3:0 DLC"),
    ("c_can_rx_data_addr", 0x40000320, "CAN", "R", "Received data bytes 0-3"),
    ("c_can_rx_data_hi_addr", 0x40000324, "CAN", "R", "Received data bytes 4-7"),
    ("c_can_rx_status_addr", 0x40000328, "CAN", "RW", "1 overrun, 0 frame waiting; a word write releases the frame"),
    ("c_can_rx_irq_en_addr", 0x4000032C, "CAN", "RW", "0 enables the received-frame interrupt"),
    ("c_ram_base_addr", 0x20000000, "RAM", "RW", "First byte of the 256 KB ECC RAM"),
    ("c_ecc_sbe_count_addr", 0x40000100, "ECC", "R", "Corrected single-bit errors, 15:0, saturating"),
    ("c_ecc_dbe_count_addr", 0x40000104, "ECC", "R", "Uncorrectable errors, 15:0"),
    ("c_ecc_syndrome_addr", 0x40000108, "ECC", "R", "Syndrome of the last error"),
    ("c_ecc_status_addr", 0x4000010C, "ECC", "R", "Worst error seen: 0 none, 1 SBE, 2 DBE"),
    ("c_wd_kick_addr", 0x40000200, "Watchdog", "W", "A word write of 0x0000DEAD kicks the watchdog"),
    ("c_wd_status_addr", 0x40000204, "Watchdog", "R", "7 violation held, 6 early, 5 late, 4:0 counter 15:11"),
    ("c_wd_reset_src_addr", 0x40000208, "Watchdog", "R", "Last watchdog reset: 0 none, 1 early, 2 late"),
    ("c_uart_tx_data_addr", 0x40000400, "UART", "W", "Byte to send, in 7:0; any store that includes byte 0"),
    ("c_uart_status_addr", 0x40000404, "UART", "RW", "1 parity error interrupt, 0 busy; a write clears the interrupt"),
    ("c_uart_parity_addr", 0x40000408, "UART", "R", "0 the held byte has good parity"),
]


def vhdl_lines():
    width = max(len(name) for name, *_ in REGISTERS)
    return [f"  constant {name:<{width}} : std_logic_vector(c_addr_width - 1 downto 0) := x\"{addr:08X}\";"
            for name, addr, *_ in REGISTERS]


def write_package():
    text = PACKAGE.read_text(encoding="utf-8").replace("\r\n", "\n")
    lines = text.split("\n")
    start, stop = lines.index(BEGIN), lines.index(END)
    lines[start + 1:stop] = vhdl_lines()
    PACKAGE.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def c_name(name):
    return "LOCKSTEP_" + name[2:-5].upper()


def write_header():
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    width = max(len(c_name(name)) for name, *_ in REGISTERS)
    body = [f"#define {c_name(name):<{width}} 0x{addr:08X}u  /* {access:2} {meaning} */"
            for name, addr, _, access, meaning in REGISTERS]
    HEADER.write_text(
        "/* Generated by sim/scripts/register_map.py. Do not edit: change the table there. */\n"
        "/* lockstep-rv32-soc register addresses, HSI-LRS-001 sections 3 and 5.1. */\n\n"
        "#ifndef LOCKSTEP_SOC_REGS_H\n#define LOCKSTEP_SOC_REGS_H\n\n"
        "#define LOCKSTEP_WD_KICK_KEY 0x0000DEADu\n\n" + "\n".join(body) + "\n\n#endif\n",
        encoding="utf-8", newline="\n")


def write_doc():
    rows = [f"| `0x{addr:08X}` | {block} | `{name}` | `{c_name(name)}` | {access} | {meaning} |"
            for name, addr, block, access, meaning in sorted(REGISTERS, key=lambda r: r[1])]
    DOC.write_text(
        "# Register map\n\n"
        "Generated by `sim/scripts/register_map.py` from its `REGISTERS` table, which is\n"
        "the single source for the RTL constants, the C header and this page. Do not edit\n"
        "here. Access and decode rules are in HSI section 8.1: an address in the window\n"
        "that is not listed answers ERR.\n\n"
        "| Address | Block | VHDL constant | C macro | Access | Meaning |\n"
        "|---------|-------|---------------|---------|--------|---------|\n" + "\n".join(rows) + "\n",
        encoding="utf-8", newline="\n")


def main():
    write_package()
    write_header()
    write_doc()
    print(f"{len(REGISTERS)} registers written to {PACKAGE.name}, {HEADER.name} and {DOC.name}")


if __name__ == "__main__":
    main()
